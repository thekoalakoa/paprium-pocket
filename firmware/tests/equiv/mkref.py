"""mkref.py - build a REFERENCE host executable of a shipped firmware tree, independently of paprium-fw's board/host
(stage 0, the tree's first step; written first outside this tree, with the same logic and fixed paths).

    python -I -B tests/equiv/mkref.py --src <final 0.2.6 sources> --md5 <its src_md5.txt> --harness <audit harness dir>
                                      --out <dir outside the tree> --name final026 [--variant test|release]

The reference = the shipped sources (md5-checked), the own host driver of the audit harness (our test harness outside
this tree: its ours_host.c, md5 9799ff8b) and its build flags (gcc -O1
-funsigned-char -fno-strict-aliasing -w). Edges written for the reference only:
  * ours_host_ref.c = ours_host.c + GPIO_INPUT variable + 'O' request (paprium-fw's encoding) + buddy_event() stub;
  * the shim's appmain.h = the harness shim + final 0.2.6's printf rule (PPM_DEBUG_PRINTF 0 -> empty inline printf);
  * paprium.c COPY: the one RISC-V inline-asm statement the unity build compiles (ppm_start's srli+andi pair) becomes
    the C statement with the same result. A different technique from board/host's GNU as macros, on purpose.
Nothing is written inside the tree."""
import argparse, hashlib, os, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UNITY = ('mame.c', 'mame.h', 'paprium.c', 'paprium.h', 'cfg.h', 'sfx.h', 'mdp.h', 'everdrive.h', 'buddy.h')
ASM_OLD = '__asm__ ("srli %0, %1, 3\\n\\tandi %0, %0, %2" : "=r" (hit) : "r" (ctrl), "i" (BUDDY_LOOP_MASK));'
ASM_NEW = 'hit = (ctrl >> 3) & (BUDDY_LOOP_MASK);   /* equiv/refhost: x86 form of the srli+andi pair */'
SHIM = r'''/* equiv/refhost shim: appmain.h of the audit harness shim + final 0.2.6's printf rule + GPIO_INPUT (mkref.py). */
#ifndef APPMAIN_H
#define APPMAIN_H
#include <stdint.h>
#include <stddef.h>
#include <string.h>
#include <stdio.h>
#include <stdlib.h>
#include <stdarg.h>
extern volatile uint32_t host_gpio_input;
#define GPIO_INPUT host_gpio_input
#include "cfg.h"
#include "mame.h"
#include "paprium.h"
#include "sfx.h"
#include "mdp.h"
#include "everdrive.h"
int host_printf(const char *fmt, ...);
#if defined(PPM_DEBUG_PRINTF) && !PPM_DEBUG_PRINTF
static inline __attribute__((always_inline)) void ppm_printf_off(const char *format, ...) { (void) format; }
#define printf ppm_printf_off
#else
#define printf host_printf
#endif
void printHex(void *src, u32 size);
#endif
'''


def md5b(b):
    return hashlib.md5(b).hexdigest()


def edit(text, anchor, new):
    if '\r\n' in text:
        anchor, new = anchor.replace('\n', '\r\n'), new.replace('\n', '\r\n')
    assert text.count(anchor) == 1, (anchor, text.count(anchor))
    return text.replace(anchor, new)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', required=True)
    ap.add_argument('--md5', help="the tree's src_md5.txt (checked when given)")
    ap.add_argument('--harness', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--name', required=True)
    ap.add_argument('--variant', action='append', choices=('test', 'release'))
    ap.add_argument('--gcc', default='gcc')
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    assert not out.startswith(ROOT), 'refusing to write inside the tree'
    if a.md5:
        for ln in open(a.md5):
            h, f = ln.split()
            p = os.path.join(os.path.dirname(a.md5), f.lstrip('*'))
            assert md5b(open(p, 'rb').read()) == h, p
    hc = open(os.path.join(a.harness, 'ours', 'ours_host.c'), 'rb').read()
    assert md5b(hc) == '9799ff8b285ebddbaf2ac2e4280659d0', md5b(hc)
    t = hc.decode('latin-1')
    t = edit(t, 'int host_map(void);\n',
             'int host_map(void);\n'
             'volatile uint32_t host_gpio_input = 0;   /* equiv/refhost: GPIO_INPUT (appmain.h of the shim) */\n'
             'void buddy_event(uint32_t ctrl) { (void) ctrl; }   /* equiv/refhost: only ppm_start calls it */\n')
    t = edit(t, "        } else if (op == 'G') {\n",
             "        } else if (op == 'O') {   /* equiv/refhost: option word for the next 'R' (paprium-fw encoding) */\n"
             "            uint32_t w; rd(&w, 4); host_gpio_input = w;\n"
             "            wr(\"k\", 1);\n"
             "        } else if (op == 'G') {\n")
    t = '/* equiv/refhost: GENERATED by mkref.py from ours_host.c of the audit harness (9799ff8b); edits marked. */\n' + t
    os.makedirs(os.path.join(out, 'shim'), exist_ok=True)
    open(os.path.join(out, 'ours_host_ref.c'), 'wb').write(t.encode('latin-1'))
    open(os.path.join(out, 'shim', 'appmain.h'), 'w', newline='\n').write(SHIM)
    shutil.copyfile(os.path.join(a.harness, 'ours', 'memmap.c'), os.path.join(out, 'memmap.c'))
    dst = os.path.join(out, 'src_' + a.name)
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    os.makedirs(dst)
    for f in UNITY:
        shutil.copyfile(os.path.join(a.src, f), os.path.join(dst, f))
    p = os.path.join(dst, 'paprium.c')
    txt = open(p, 'rb').read().decode('latin-1')
    open(p, 'wb').write(edit(txt, ASM_OLD, ASM_NEW).encode('latin-1'))
    env = dict(os.environ, PATH=os.path.dirname(a.gcc) + os.pathsep + os.environ.get('PATH', ''))
    for var in a.variant or ['test', 'release']:
        exe = os.path.join(out, 'bin', '%s_%s.exe' % (a.name, var))
        os.makedirs(os.path.dirname(exe), exist_ok=True)
        cmd = [a.gcc, '-O1', '-funsigned-char', '-fno-strict-aliasing', '-w'] + (['-DPPM_RELEASE=1'] if var == 'release' else []) + \
              ['-I', os.path.join(out, 'shim'), '-I', dst, os.path.join(out, 'ours_host_ref.c'), os.path.join(out, 'memmap.c'), '-o', exe]
        r = subprocess.run(cmd, capture_output=True, text=True, env=env)
        if r.returncode:
            sys.exit(r.stderr[-3000:])
        print('%s %s -> %s md5 %s' % (a.name, var, exe, md5b(open(exe, 'rb').read())))


if __name__ == '__main__':
    main()
