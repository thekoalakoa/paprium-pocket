"""gen_c5_curve.py - the synth's output curve in the boot overlay's packed form (board/pocket/boot/c5_curve.h; the c5
in the names comes from test build 5, the hardware test build that first carried it).

    python -I -B board/pocket/boot/gen_c5_curve.py            # (re)write c5_curve.h next to this file
    python -I -B board/pocket/boot/gen_c5_curve.py --check    # exit 1 unless the file on disk is what this writes

The synth reads the cart chip's output curve from CRAM (docs/MCU_INTERFACE.md v1.3 3.8 CURVE_WIN: 16,384 x u16 at
0x194000-0x19BFFF, index 0 of the input at 0x198000), and the firmware writes it there at boot. The curve is
core/tables/gen_chip_tables.py's. Its stored part would cost 4,928 B (chip_tables.c chip_out_curve_knee); the overlay
instead keeps a packed form of 488 B and rebuilds both halves of the curve while it writes them (c4b_ovl.c
curve_write). No byte comes from the cart program. This tool checks that the packed form fits and that the rebuilt
curve equals gen_chip_tables.curve_full() entry for entry. The tables were worked out from our own study of how the
cart behaves and checked on hardware."""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, os.path.join(ROOT, 'core', 'tables'))
import gen_chip_tables as g   # noqa: E402

LIN = 512                      # where the packed steps start


def q_of(m):
    """one value of gen_chip_tables.curve_F's first stage"""
    if 2 * m + 1 <= 1024:
        return 2 * m + 1
    z = (g.Decimal(2 * m + 1) - 1024) / 1024
    return g._floor('curve', 1024 + 1024 * g._tanh(z))


def build():
    knee = g.curve_knee()
    n = len(knee)
    assert n == g.CURVE_KNEE_N and all(q_of(m) <= 1023 for m in range(LIN))
    steps = []
    for m in range(LIN, n):
        d = q_of(m) - q_of(m - 1)
        if not 0 <= d <= 2:
            raise SystemExit('step %d at m=%d does not fit two bits' % (d, m))
        steps.append(d)
    while len(steps) % 4:
        steps.append(0)
    packed = [steps[i] | steps[i + 1] << 2 | steps[i + 2] << 4 | steps[i + 3] << 6 for i in range(0, len(steps), 4)]
    # the overlay's rebuild, here in Python, against the generator's full curve
    full = g.curve_full(knee)
    out = [None] * 16384
    q = 0
    for m in range(8193):
        if m < LIN:
            q = 2 * m + 1
        elif m < n:
            k = m - LIN
            q += (packed[k >> 2] >> (2 * (k & 3))) & 3
        f = (61 * q) >> 6 if m < n else g.CURVE_PLATEAU
        if m < 8192:
            out[8192 + m] = 2047 + f
        if m:
            out[8192 - m] = 2047 - f
    if out != full:
        bad = [i for i in range(16384) if out[i] != full[i]]
        raise SystemExit('the packed curve differs from curve_full at %d entries (first %d)' % (len(bad), bad[0]))
    return packed, n


def text(packed, n):
    lines = ['/* Copyright (C) 2026 Marsupial Solutions LLC',
             '   SPDX-License-Identifier: GPL-3.0-or-later */',
             '/* board/pocket/boot/c5_curve.h - GENERATED by gen_c5_curve.py, do not edit.',
             ' *',
             ' * The synth\'s output curve (test build 5 on; docs/MCU_INTERFACE.md v1.3 3.8 CURVE_WIN) in a packed form, as',
             ' * the boot overlay writes it into CRAM (c4b_ovl.c curve_write). Equal to core/tables/gen_chip_tables.py',
             ' * curve_full() at every one of the 16,384 entries (checked by the generator). The tables were worked out',
             ' * from our own study of how the cart behaves and checked on hardware.',
             ' */',
             '#ifndef C5_CURVE_H',
             '#define C5_CURVE_H',
             '#include <stdint.h>',
             '',
             '#define C5_CURVE_LIN            %du' % LIN,
             '#define C5_CURVE_KNEE_N         %du' % n,
             '#define C5_CURVE_PLATEAU        %du' % g.CURVE_PLATEAU,
             '#define C5_CURVE_STEP_BYTES     %du' % len(packed),
             '',
             'static const uint8_t c5_curve_step[C5_CURVE_STEP_BYTES] = {']
    for i in range(0, len(packed), 16):
        lines.append('    ' + ', '.join('0x%02X' % v for v in packed[i:i + 16]) + ',')
    lines += ['};', '', '#endif', '']
    return '\n'.join(lines)


def main():
    packed, n = build()
    t = text(packed, n)
    p = os.path.join(HERE, 'c5_curve.h')
    if '--check' in sys.argv[1:]:
        cur = open(p, 'r', encoding='utf-8', newline='').read() if os.path.exists(p) else ''
        if cur != t:
            print('c5_curve.h is not what gen_c5_curve.py writes')
            sys.exit(1)
        print('c5_curve.h OK: %d step bytes, the rebuilt curve == curve_full (16,384 entries)' % len(packed))
        return
    open(p, 'w', encoding='utf-8', newline='\n').write(t)
    print('wrote', p, '(%d step bytes; the rebuilt curve == curve_full at all 16,384 entries)' % len(packed))


if __name__ == '__main__':
    main()
